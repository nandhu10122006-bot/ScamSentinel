-- CyberSentry PostgreSQL Database Schema
-- Compatible with PostgreSQL / Neon

CREATE TABLE IF NOT EXISTS scan_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_url TEXT NOT NULL,
    normalized_url TEXT,
    classification VARCHAR(30) NOT NULL,
    risk_score INTEGER
        CHECK (risk_score BETWEEN 0 AND 100),
    explanation TEXT,
    scanned_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS url_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL
        REFERENCES scan_history(id) ON DELETE CASCADE,
    indicator_name VARCHAR(100) NOT NULL,
    description TEXT,
    detected BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS qr_scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT
        REFERENCES scan_history(id) ON DELETE CASCADE,
    qr_format VARCHAR(30),
    extracted_url TEXT,
    scanned_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS threat_indicators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_type VARCHAR(50) NOT NULL,
    indicator_value TEXT NOT NULL,
    source VARCHAR(150),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (indicator_type, indicator_value)
);

CREATE TABLE IF NOT EXISTS feedback_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT
        REFERENCES scan_history(id) ON DELETE SET NULL,
    report_type VARCHAR(50) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for common lookups
CREATE INDEX IF NOT EXISTS idx_scan_history_scanned_at
    ON scan_history (scanned_at DESC);

CREATE INDEX IF NOT EXISTS idx_scan_history_classification
    ON scan_history (classification);

CREATE INDEX IF NOT EXISTS idx_url_analysis_scan_id
    ON url_analysis (scan_id);

CREATE INDEX IF NOT EXISTS idx_qr_scans_scan_id
    ON qr_scans (scan_id);

CREATE INDEX IF NOT EXISTS idx_feedback_reports_scan_id
    ON feedback_reports (scan_id);